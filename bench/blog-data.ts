#!/usr/bin/env bun
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/*
 * Writes the numbers for a post about vue-check as a TypeScript module, from
 * bench/results only (as bench/table.ts does for the README), so a post never
 * carries a hand-typed figure.
 *
 *   bun bench/blog-data.ts <output.ts>
 */

type Phases = { checkMB: number; checkS: number; codegenMB: number; codegenS: number; mapMB: number; mapS: number; vueFiles: number };
type Tool = { errors: number; medianPeakRssMB: number; medianWallS: number; phases?: Phases };
type Result = {
	bunCheckMatchesTsc7: boolean;
	environment: Record<string, string | number>;
	identical: boolean;
	runs: number;
	summary: Record<string, Tool>;
	typeScript7Changes: { added: string[]; removed: string[] };
};

const output = process.argv[2];
if (!output) throw new Error('usage: bun bench/blog-data.ts <output.ts>');
const directory = join(import.meta.dir, 'results');
const read = <T>(file: string) => JSON.parse(readFileSync(join(directory, file), 'utf8')) as T;
const files = readdirSync(directory)
	.filter((file) => file.endsWith('.json') && !file.endsWith('.raw.json') && file !== 'conformance.json')
	.sort();

const projects = files
	.map((file) => ({ name: file.replace(/\.json$/, ''), result: read<Result>(file) }))
	.filter(({ name }) => !name.includes('planted'))
	.map(({ name, result }) => {
		const vueTsc = result.summary['vue-tsc'];
		const vueCheck = result.summary['vue-check'];
		const single = result.summary['vue-check (1 thread)'];
		if (!vueTsc || !vueCheck || !single || !vueCheck.phases) throw new Error(`${name}: incomplete result`);

		return {
			bunMatchesTsc7: result.bunCheckMatchesTsc7,
			errors: vueTsc.errors,
			identical: result.identical,
			name,
			phases: {
				checkMB: vueCheck.phases.checkMB,
				checkS: vueCheck.phases.checkS,
				codegenMB: vueCheck.phases.codegenMB,
				codegenS: vueCheck.phases.codegenS,
				mapMB: vueCheck.phases.mapMB,
				mapS: vueCheck.phases.mapS,
				vueFiles: vueCheck.phases.vueFiles
			},
			runs: result.runs,
			single: { mb: single.medianPeakRssMB, s: single.medianWallS },
			typeScript7Changes: result.typeScript7Changes.added.length + result.typeScript7Changes.removed.length,
			vueCheck: { mb: vueCheck.medianPeakRssMB, s: vueCheck.medianWallS },
			vueTsc: { mb: vueTsc.medianPeakRssMB, s: vueTsc.medianWallS, version: String(result.environment.vueTsc) }
		};
	})
	.sort((a, b) => b.vueTsc.s - a.vueTsc.s);

const planted = read<Result>('vue-pure-admin-planted-errors.json');
const conformance = read<{ bunMatchesTsc7: number; cases: number; failing: { name: string }[]; identical: number }>('conformance.json');
const environment = read<Result>(files.find((file) => file.startsWith('vue-pure-admin.')) ?? files[0] ?? '').environment;

const data = {
	conformance: {
		bunMatchesTsc7: conformance.bunMatchesTsc7,
		cases: conformance.cases,
		different: conformance.failing.map((item) => item.name),
		identical: conformance.identical
	},
	environment: {
		bun: String(environment.bun),
		containerMemoryLimit: String(environment.containerMemoryLimit),
		cpu: String(environment.cpu),
		node: String(environment.node),
		totalMemoryGB: Number(environment.totalMemoryGB),
		tsc7: String(environment.tsc7).replace('Version ', '')
	},
	planted: {
		bunMatchesTsc7: planted.bunCheckMatchesTsc7,
		identical: planted.identical,
		reported: planted.summary['vue-tsc']?.errors ?? 0
	},
	projects
};

/* Keys sorted at every level, as the docs' lint requires. */
const sorted = (value: unknown): unknown =>
	Array.isArray(value)
		? value.map(sorted)
		: value !== null && typeof value === 'object'
			? Object.fromEntries(
					Object.entries(value)
						.sort(([first], [second]) => first.localeCompare(second))
						.map(([key, entry]) => [key, sorted(entry)])
				)
			: value;
const TYPE = `type Measure = { mb: number; s: number };

type ProjectResult = {
	bunMatchesTsc7: boolean;
	errors: number;
	identical: boolean;
	name: string;
	phases: { checkMB: number; checkS: number; codegenMB: number; codegenS: number; mapMB: number; mapS: number; vueFiles: number };
	runs: number;
	single: Measure;
	typeScript7Changes: number;
	vueCheck: Measure;
	vueTsc: Measure & { version: string };
};

type VueCheckResults = {
	conformance: { bunMatchesTsc7: number; cases: number; different: string[]; identical: number };
	environment: { bun: string; containerMemoryLimit: string; cpu: string; node: string; totalMemoryGB: number; tsc7: string };
	planted: { bunMatchesTsc7: boolean; identical: boolean; reported: number };
	projects: ProjectResult[];
};`;
writeFileSync(
	output,
	`// Generated by vue-check's bench/blog-data.ts from its bench/results. Do not edit by hand.\n\n${TYPE}\n\nexport const vueCheckResults: VueCheckResults = ${JSON.stringify(sorted(data), null, '\t')};\n`
);
console.log(`wrote ${projects.length} projects to ${output}`);
